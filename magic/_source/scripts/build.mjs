import { build } from 'vite';
import { createHash } from 'node:crypto';
import { copyFile, lstat, mkdir, readFile, readdir, realpath, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const sourceDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const deployDirectory = path.resolve(sourceDirectory, '..');
const releaseDirectory = path.join(sourceDirectory, '.release');
const allowedFiles = new Set(['index.html', 'manifest.webmanifest', 'assets-credit.json', 'sw.js']);
const allowedDirectories = new Set(['engine', 'models', 'icons', 'licenses']);

async function statIfPresent(target) {
  try { return await lstat(target); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

async function requirePlainDirectory(directory, optional = false) {
  const stat = await statIfPresent(directory);
  if (!stat && optional) return;
  if (!stat?.isDirectory() || stat.isSymbolicLink()) {
    throw new Error(`Απαιτείται κανονικός φάκελος, χωρίς συμβολικό σύνδεσμο: ${directory}`);
  }
}

function within(root, relative) {
  const target = path.resolve(root, relative);
  const difference = path.relative(root, target);
  if (!difference || difference === '..' || difference.startsWith(`..${path.sep}`) || path.isAbsolute(difference)) {
    throw new Error(`Μη ασφαλής διαδρομή εξόδου: ${relative}`);
  }
  return target;
}

async function listFiles(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isSymbolicLink()) throw new Error(`Δεν επιτρέπεται συμβολικός σύνδεσμος στο build: ${entry.name}`);
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await listFiles(path.join(directory, entry.name), relative));
    else if (entry.isFile()) files.push(relative);
    else throw new Error(`Μη υποστηριζόμενο αρχείο build: ${relative}`);
  }
  return files.sort();
}

function validateDeployFile(relative) {
  const parts = relative.split('/');
  if (parts.some(part => !part || part === '.' || part === '..' || part.startsWith('.'))) {
    throw new Error(`Μη ασφαλές αρχείο build: ${relative}`);
  }
  if (parts.length === 1 ? !allowedFiles.has(parts[0]) : !allowedDirectories.has(parts[0])) {
    throw new Error(`Το build περιέχει μη εγκεκριμένη διαδρομή δημοσίευσης: ${relative}`);
  }
  within(releaseDirectory, relative);
  within(deployDirectory, relative);
}

async function validateDestination(relative) {
  const segments = relative.split('/');
  for (let index = 1; index <= segments.length; index++) {
    const target = within(deployDirectory, segments.slice(0, index).join('/'));
    const stat = await statIfPresent(target);
    if (!stat) continue;
    if (stat.isSymbolicLink()) throw new Error(`Η δημοσίευση δεν ακολουθεί συμβολικούς συνδέσμους: ${target}`);
    const expectsDirectory = index < segments.length;
    if (expectsDirectory ? !stat.isDirectory() : !stat.isFile()) {
      throw new Error(`Η διαδρομή δημοσίευσης έχει απροσδόκητο τύπο: ${target}`);
    }
  }
}

function serviceWorkerSource(files, buildHash) {
  const urls = files.map(file => file.split('/').map(encodeURIComponent).join('/'));
  return `/* Generated by _source/scripts/build.mjs. Runtime assets are scoped to this app. */
'use strict';
const SCOPE = new URL(self.registration.scope);
const INDEX_URL = new URL('index.html', SCOPE).href;
const CACHE_PREFIX = 'magic-exiled:' + SCOPE.pathname + ':';
const CACHE_NAME = CACHE_PREFIX + ${JSON.stringify(buildHash)};
const PRECACHE = ${JSON.stringify(urls, null, 2)}.map(file => new URL(file, SCOPE).href);

function isInScope(url) {
  return url.origin === SCOPE.origin && url.pathname.startsWith(SCOPE.pathname);
}

function mayCache(response) {
  return response.ok && response.status !== 206 && response.type !== 'opaque'
    && (!response.url || isInScope(new URL(response.url)));
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    // addAll rejects a failed or partial response; HTTP errors are never stored.
    await cache.addAll(PRECACHE.map(url => new Request(url, { cache: 'reload', credentials: 'same-origin' })));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME).map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});

async function navigation(request, url) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const response = await fetch(request);
    if (mayCache(response)) {
      const canonical = url.pathname === SCOPE.pathname || url.pathname === new URL(INDEX_URL).pathname;
      await cache.put(canonical ? INDEX_URL : request, response.clone()).catch(() => {});
      return response;
    }
    return await cache.match(INDEX_URL) || response;
  } catch {
    return await cache.match(INDEX_URL) || await cache.match(request)
      || new Response('Το MAGIC χρειάζεται μία ολοκληρωμένη πρώτη φόρτωση με σύνδεση.', {
        status: 503,
        headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' }
      });
  }
}

async function asset(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (mayCache(response)) await cache.put(request, response.clone()).catch(() => {});
  return response;
}

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || request.headers.has('range')) return;
  const url = new URL(request.url);
  if (!isInScope(url)) return;
  event.respondWith(request.mode === 'navigate' ? navigation(request, url) : asset(request));
});
`;
}

async function main() {
  const projectName = path.basename(deployDirectory);
  const expectedName = process.platform === 'win32' ? projectName.toLowerCase() : projectName;
  if (path.basename(sourceDirectory) !== '_source' || expectedName !== 'magic') {
    throw new Error('Το script δημοσιεύει αποκλειστικά από magic/_source προς magic.');
  }
  await requirePlainDirectory(sourceDirectory);
  await requirePlainDirectory(deployDirectory);
  await requirePlainDirectory(releaseDirectory, true);
  if (await realpath(sourceDirectory) !== sourceDirectory || await realpath(deployDirectory) !== deployDirectory) {
    throw new Error('Οι φάκελοι πηγής και δημοσίευσης πρέπει να είναι πραγματικές διαδρομές.');
  }

  // The complete build must succeed before any deployed file is replaced.
  await build({
    root: sourceDirectory,
    configFile: path.join(sourceDirectory, 'vite.config.js'),
    build: { outDir: releaseDirectory, emptyOutDir: true, assetsDir: 'engine', copyPublicDir: false },
  });

  // Local static QA previews live under public/.cache on the shared server.
  // Copy deliverable public assets explicitly so those previews cannot enter a release.
  const publicDirectory = path.join(sourceDirectory, 'public');
  const publicFiles = (await listFiles(publicDirectory)).filter(file =>
    !file.split('/').some(part => part.startsWith('.')));
  for (const file of publicFiles) {
    validateDeployFile(file);
    const target = within(releaseDirectory, file);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(within(publicDirectory, file), target);
  }

  // Vite's inserted asset tags use LF even when a Windows checkout uses CRLF.
  // Normalize before hashing so mixed CR characters cannot enter the release.
  const htmlFile = within(releaseDirectory, 'index.html');
  await writeFile(htmlFile, (await readFile(htmlFile, 'utf8')).replace(/\r\n?/g, '\n'));

  const files = (await listFiles(releaseDirectory)).filter(file => file !== 'sw.js');
  for (const file of files) validateDeployFile(file);
  for (const required of ['index.html', 'manifest.webmanifest', 'icons/magic-rune.svg', 'icons/apple-touch-icon.png', 'icons/magic-192.png', 'icons/magic-512.png', 'models/mage.glb', 'models/guard.glb', 'models/archer.glb', 'models/heavy.glb']) {
    if (!files.includes(required)) throw new Error(`Λείπει απαραίτητο αρχείο από το build: ${required}`);
  }
  if (!files.some(file => file.startsWith('engine/') && file.endsWith('.js'))) throw new Error('Το build δεν παρήγαγε το runtime του παιχνιδιού.');

  const digest = createHash('sha256');
  digest.update(serviceWorkerSource(files, 'BUILD_HASH'));
  let bytes = 0;
  for (const file of files) {
    const content = await readFile(within(releaseDirectory, file));
    bytes += content.length;
    digest.update(file + '\0' + content.length + '\0');
    digest.update(content);
  }
  const buildHash = digest.digest('hex').slice(0, 24);
  await writeFile(path.join(releaseDirectory, 'sw.js'), serviceWorkerSource(files, buildHash));
  const deployFiles = [...files, 'sw.js'];
  for (const file of deployFiles) {
    validateDeployFile(file);
    await validateDestination(file);
  }

  // This is the only deployed directory removed by this script. Source files,
  // README, other games, and unrelated files in magic remain untouched.
  const oldEngine = within(deployDirectory, 'engine');
  await requirePlainDirectory(oldEngine, true);
  await rm(oldEngine, { recursive: true, force: true });

  for (const file of deployFiles) {
    const target = within(deployDirectory, file);
    await mkdir(path.dirname(target), { recursive: true });
    await copyFile(within(releaseDirectory, file), target);
  }
  console.log(`MAGIC: ${deployFiles.length} αρχεία δημοσίευσης, ${(bytes / 1024 / 1024).toFixed(2)} MiB runtime, offline cache ${buildHash}.`);
}

main().catch(error => {
  console.error('Η δημιουργία του MAGIC απέτυχε:', error.message);
  process.exitCode = 1;
});
